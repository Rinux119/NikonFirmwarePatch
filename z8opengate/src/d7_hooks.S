/* D7 = D6 + the open-gate flag follows an i-menu cancel (data-store rollback) + the joins needed to carry the
 * nraw-tenc-rate Q3 four N-RAW quality tiers in the same payload.
 *
 * Body evidence (D6, 2026-10-27, d6_body_20261027): the cancel callback of the i-menu "frame size / rate" list
 * (item AB, descriptor 43A1E828, slot +0x30 = 404DB3BC -> 403EC5A4) rolls the data store back to the values the
 * list was opened with (410D8400(0)); the open-gate flag A03D5C02B is not a data-store item.  Open gate -> 60p ->
 * cancel gave ordinary 16:9 at the entry rate (open gate lost).  Ordinary 24p -> open gate 24p -> cancel: 3:2 LV, then
 * the whole 3:2 picture squeezed into the 16:9 band, LV no longer followed the selection, power-off hung.  QEMU control
 * traces of the shipped D6 bytes (qemu_trace/cancel-trace-d6-{a,b,c}.json): in the second direction the rollback's
 * 125A write passes setting_normal_hook with transaction marker 0 and flag 1, so that hook clears the flag and forces a
 * change notification in the middle of the native rollback (the flag is right afterwards, the order is not the one
 * of the working cursor path); in the first direction nothing restores the flag.
 *
 * Change (all four calls of 410D8400: 403EC594 commit, 403EC5C8 rollback, 410E764C, 410E7EE8 inside the store):
 *   i_list_apply_hook  the first list apply (403EC508 path) of a session stores the flag the session started with in
 *                      OG_STATE+0x1C (bit 8 valid, bits 0..7 flag); OG_STATE+0x1C was reserved (no D3..D6 reader or
 *                      writer) and is cleared with the rest of OG_STATE at the text-restore boundary
 *   ds_session_end_hook  every session end clears the snapshot; a rollback with a snapshot first writes the entry
 *                      flag back and sets the transaction marker (2 = flag changes, 1 = not) around the native
 *                      rollback, the order the cursor and main-menu transactions already use (flag first, then the
 *                      native call).  The native rollback writes 125A through 41015D6C (QEMU, D6 control traces), so
 *                      with marker 2 setting_normal_hook forces the setting change notification even when the
 *                      canonical size/rate is the same (ordinary 30p <-> open-gate 30p), and with marker 1 or 2 it
 *                      no longer applies its "ordinary write clears the flag" rule in the middle of the rollback
 * Q3 joins (the Q3 tier code itself is generated by the nraw-tenc-rate builder and placed by build_d7.py):
 *   tier_table_hook    40D1E650 (madd of the RAW bit-rate record lookup, the join of every branch): when Q3 chose its
 *                      Fine or Basic record table and the open-gate flag is 1, use the open-gate copy of that table
 *                      (8.3K 30/25/24p records 8268x5512 with full-height Fine/Basic rates); everything else unchanged
 *   boot_reset_hook    41184DE8 is hooked by both lines: clears the Q3 stash word as Q3 did, then the D6 hook
 */
#if WITH_Q3
#define boot_reset_hook boot_reset_hook_d6
#endif
#define i_list_apply_hook i_list_apply_hook_d6
#include "d6_hooks.S"
#undef boot_reset_hook
#undef i_list_apply_hook
#define SNAP_VALID 8

.text
.balign 16
.global i_list_apply_hook
i_list_apply_hook:
    ldr x16, =OG_STATE
    ldr w17, [x16, #0x1c]
    tbnz w17, #SNAP_VALID, 1f
    ldr x17, =OG_FLAG
    ldrb w17, [x17]
    orr w17, w17, #(1 << SNAP_VALID)
    str w17, [x16, #0x1c]
1:  b i_list_apply_hook_d6

/* w0 = 1 commit / 0 rollback; replaces bl 410D8400 at its four call sites; returns the native result. */
.balign 16
.global ds_session_end_hook
ds_session_end_hook:
    stp x19, x20, [sp, #-48]!
    stp x21, x22, [sp, #16]
    stp x23, x30, [sp, #32]
    mov w19, w0
    ldr x20, =OG_STATE
    ldr w21, [x20, #0x1c]
    str wzr, [x20, #0x1c]
    tbz w21, #SNAP_VALID, 8f
    tbnz w19, #0, 8f
    ldr x9, =OG_FLAG
    ldrb w10, [x9]
    and w21, w21, #0xff
    ldr w22, [x20, #0x14]
    cmp w21, w10
    cset w11, ne
    add w11, w11, #1
    str w11, [x20, #0x14]
    strb w21, [x9]
    mov w0, wzr
    bl original_410D8400
    str w22, [x20, #0x14]
    b 9f
8:  mov w0, w19
    bl original_410D8400
9:  ldp x23, x30, [sp, #32]
    ldp x21, x22, [sp, #16]
    ldp x19, x20, [sp], #48
    ret

#if WITH_Q3
/* x9 = record index, x10 = record table, w8 = 0x18 (stock 40D1E650 madd x8,x9,x8,x10). */
.balign 16
.global tier_table_hook
tier_table_hook:
    stp x11, x12, [sp, #-16]!
    ldr x11, =Q3_FINE_TABLE
    cmp x10, x11
    b.eq 1f
    ldr x11, =Q3_BASIC_TABLE
    cmp x10, x11
    b.ne 9f
1:  ldr x11, =OG_FLAG
    ldrb w11, [x11]
    cmp w11, #1
    b.ne 9f
    ldr x11, =OG_TIER_DELTA
    add x10, x10, x11
9:  ldp x11, x12, [sp], #16
    madd x8, x9, x8, x10
    b original_40D1E654

.balign 16
.global boot_reset_hook
boot_reset_hook:
    cmp w19, #1
    b.ne 1f
    stp x8, x9, [sp, #-16]!
    ldr x8, =Q3_STASH_RAM
    stp xzr, xzr, [x8]
    ldp x8, x9, [sp], #16
1:  b boot_reset_hook_d6
#endif
.ltorg
